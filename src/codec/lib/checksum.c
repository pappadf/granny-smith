uint64_t codec_crc64(uint64_t crc, const void *data, size_t len) {
    const uint8_t *p = (const uint8_t *)data;
    crc = ~crc;
    for (size_t i = 0; i < len; i++)
        crc = k_crc64_table[(crc ^ p[i]) & 0xFFu] ^ (crc >> 8);
    return ~crc;
}

