uint64_t codec_crc64(uint64_t crc, const void *data, size_t len) {
    const uint8_t *p = (const uint8_t *)data;
    crc = ~crc;
    for (size_t i = 0; i < len; i++)
        crc = k_crc64_table[(crc ^ p[i]) & 0xFFu] ^ (crc >> 8);
    return ~crc;
}

// ============================================================================
// Adler-32 (zlib)
// ============================================================================

uint32_t codec_adler32(uint32_t adler, const void *data, size_t len) {
    const uint8_t *p = (const uint8_t *)data;
    uint32_t a = adler & 0xffff, b = adler >> 16;
    while (len > 0) {
        // 5552 is the most bytes that can be summed before b can overflow.
        size_t n = len < 5552 ? len : 5552;
        len -= n;
        while (n--) {
            a += *p++;
            b += a;
        }
        a %= 65521;
        b %= 65521;
    }
    return (b << 16) | a;
}
