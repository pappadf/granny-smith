uint32_t codec_crc32(uint32_t crc, const void *data, size_t len) {
    const uint8_t *p = (const uint8_t *)data;
    crc = ~crc;
    for (; len >= 8; len -= 8, p += 8) {
        uint32_t lo = crc ^ codec_le32(p), hi = codec_le32(p + 4);
        crc = k_crc32_table[7][lo & 0xFF] ^ k_crc32_table[6][(lo >> 8) & 0xFF] ^ k_crc32_table[5][(lo >> 16) & 0xFF] ^
              k_crc32_table[4][lo >> 24] ^ k_crc32_table[3][hi & 0xFF] ^ k_crc32_table[2][(hi >> 8) & 0xFF] ^
              k_crc32_table[1][(hi >> 16) & 0xFF] ^ k_crc32_table[0][hi >> 24];
    }
    while (len--)
        crc = k_crc32_table[0][(crc ^ *p++) & 0xFFu] ^ (crc >> 8);
    return ~crc;
}

// Appending zeros is linear over GF(2) on the CRC register, so it is a 32x32
// bit-matrix applied to it; len zero bytes is that matrix to the len-th
// power, built by repeated squaring (zlib's crc32_combine technique).
static uint32_t gf2_times(const uint32_t *mat, uint32_t vec) {
    uint32_t sum = 0;
    for (int i = 0; vec; i++, vec >>= 1)
        if (vec & 1)
            sum ^= mat[i];
    return sum;
}

static void gf2_square(uint32_t *square, const uint32_t *mat) {
    for (int n = 0; n < 32; n++)
        square[n] = gf2_times(mat, mat[n]);
}

uint32_t codec_crc32_zeros(uint32_t crc, uint64_t len) {
    if (len == 0)
        return crc;
    uint32_t op[32], tmp[32];
    // One zero bit: shift right, folding in the polynomial on a carry.
    op[0] = 0xEDB88320u;
    for (int n = 1; n < 32; n++)
        op[n] = 1u << (n - 1);
    gf2_square(tmp, op); // 2 bits
    gf2_square(op, tmp); // 4 bits
    gf2_square(tmp, op); // 8 bits: one zero byte
    uint32_t reg = ~crc;
    for (;;) {
        if (len & 1)
            reg = gf2_times(tmp, reg);
        len >>= 1;
        if (!len)
            break;
        gf2_square(op, tmp);
        memcpy(tmp, op, sizeof(op));
    }
    return ~reg;
}

