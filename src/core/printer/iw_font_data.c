// The language-dependent codes, and per language the alternate glyph each
// prints (index from IW_FONT_ALT), 0xFF for the ASCII glyph
static const uint8_t lang_codes[10] = {0x23, 0x40, 0x5B, 0x5C, 0x5D, 0x60, 0x7B, 0x7C, 0x7D, 0x7E};
static const uint8_t lang_alt[8][10] = {
    {0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}, // American
    {4,    5,    22,   16,   9,    25,   14,   26,   17,   27  }, // Italian
    {0xFF, 0xFF, 0,    3,    6,    0xFF, 1,    2,    11,   0xFF}, // Danish
    {4,    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}, // British
    {0xFF, 5,    8,    23,   24,   0xFF, 10,   7,    12,   13  }, // German
    {0xFF, 0xFF, 8,    23,   6,    0xFF, 10,   7,    11,   0xFF}, // Swedish
    {4,    14,   22,   16,   5,    0xFF, 9,    25,   17,   15  }, // French
    {4,    5,    18,   21,   19,   0xFF, 22,   20,   16,   0xFF}, // Spanish
};

// The glyph index for `code` under `sel`, or -1 when it prints nothing.
static int glyph_index(const iw_font_sel_t *sel, uint8_t code) {
    // High codes: $C0-$DF are MouseText, the rest print as their low halves
    if (code >= 0xC0 && code <= 0xDF)
        return IW_FONT_MOUSETEXT + (code - 0xC0);
    code &= 0x7F;
    if (code < 0x20 || code == 0x7F)
        return -1;
    if (sel->mousetext && code >= 0x40 && code <= 0x5F)
        return IW_FONT_MOUSETEXT + (code - 0x40);
    for (int i = 0; i < 10; i++)
        if (lang_codes[i] == code && lang_alt[sel->language & 7][i] != 0xFF)
            return IW_FONT_ALT + lang_alt[sel->language & 7][i];
    return code - 0x20;
}

bool iw_font_data_lookup(const iw_font_sel_t *sel, uint8_t code, iw_glyph_t *out) {
    if (sel->iw1)
        return false; // no table for the original ImageWriter yet
    if (!out)
        return true;
    int idx = glyph_index(sel, code);
    if (idx < 0)
        return false;
    memset(out, 0, sizeof(*out));
    if (sel->proportional) {
        const uint8_t *w = sel->quality == IW_QUALITY_NLQ ? iw2_nlq_prop_w : iw2_corr_prop_w;
        if (w[idx]) {
            const uint16_t *p1 = sel->quality == IW_QUALITY_NLQ ? iw2_nlq_prop[idx] : iw2_corr_prop[idx];
            for (int i = 0; i < w[idx]; i++)
                out->cols[i] = p1[i];
            out->n = w[idx];
            if (sel->quality == IW_QUALITY_NLQ) {
                for (int i = 0; i < w[idx]; i++)
                    out->pass2[i] = iw2_nlq_prop2[idx][i];
                out->n2 = w[idx];
            }
            return true;
        }
        // No proportional shape (MouseText): the fixed one, 16 columns wide,
        // NLQ's half columns taken as whole ones, correspondence doubled
        if (sel->quality == IW_QUALITY_NLQ) {
            for (int i = 0; i < 16; i++) {
                out->cols[i] = iw2_nlq1[idx][i];
                out->pass2[i] = iw2_nlq2[idx][i];
            }
            out->n2 = 16;
        } else {
            for (int i = 0; i < 16; i++)
                out->cols[i] = iw2_corr[idx][i / 2];
        }
        out->n = 16;
    } else if (sel->quality == IW_QUALITY_DRAFT) {
        // 12 half columns of shape in a 16-half-column (8 dot) cell
        for (int i = 0; i < 12; i++)
            out->cols[i] = iw2_draft[idx][i];
        out->n = 16;
        out->half = true;
    } else if (sel->quality == IW_QUALITY_NLQ) {
        for (int i = 0; i < 16; i++) {
            out->cols[i] = iw2_nlq1[idx][i];
            out->pass2[i] = iw2_nlq2[idx][i];
        }
        out->n = out->n2 = 16;
        out->half = true;
    } else {
        for (int i = 0; i < 8; i++)
            out->cols[i] = iw2_corr[idx][i];
        out->n = 8;
    }
    return true;
}
