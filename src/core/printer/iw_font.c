// The placeholder glyph for `code`: 8 columns in a fixed pitch, the shape
// doubled into 12 columns in a proportional one.
static bool placeholder_glyph(const iw_font_sel_t *sel, uint8_t code, iw_glyph_t *out) {
    code &= 0x7F;
    if (code < 0x20 || code > 0x7E)
        return false;
    const uint8_t *shape = placeholder_5x7[code - 0x20];
    memset(out, 0, sizeof(*out));
    out->placeholder = true;
    if (sel->proportional) {
        for (int i = 0; i < 5; i++)
            out->cols[1 + 2 * i] = out->cols[2 + 2 * i] = shape[i];
        out->n = 12;
    } else {
        for (int i = 0; i < 5; i++)
            out->cols[1 + i] = shape[i];
        out->n = 8;
    }
    // Slashed zero: the stroke through the oval
    if (code == '0' && sel->slash_zero && !sel->proportional) {
        out->cols[2] |= 0x20;
        out->cols[4] |= 0x02;
    }
    return true;
}

bool iw_font_has_tables(const iw_font_sel_t *sel) {
    return iw_font_data_lookup(sel, ' ', NULL);
}

bool iw_font_glyph(const iw_font_sel_t *sel, uint8_t code, iw_glyph_t *out) {
    if (iw_font_data_lookup(sel, code, out))
        return true;
    return placeholder_glyph(sel, code, out);
}
