# fcode_tokens.py
# The IEEE 1275-1994 Annex A FCode number assignments, plus the operand
# shapes the detokenizer needs to walk a token stream.
#
# Only assignments taken from the standard are listed.  A token number that
# is NOT in this table is reported by the detokenizer as `[fcode-0xNNN]`,
# never guessed at: a mis-built instrument that returns a confident wrong
# answer is worse than no instrument (an earlier hand scanner transposed two
# entries of a register table and turned a decoded fact into a "blocking
# unknown").

# Operand shapes.  A token's entry is (name, operand):
#   None    — no operand bytes
#   'lit'   — a 32-bit big-endian literal
#   'fcode' — an FCode number (1 byte, or 2 when the first is $01..$0F)
#   'str'   — an FCode string: a length byte followed by that many chars
#   'branch'— a branch offset: signed 8- or 16-bit, per the offset16 state
#   'strfc' — an FCode string followed by an FCode number (named-token)
#   'byte'  — one literal byte

