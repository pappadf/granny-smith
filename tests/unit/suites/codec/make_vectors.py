# make_vectors.py - write vectors.h, the codec suite's compressed test
# vectors, with independent encoders: Python's zlib, bz2 and lzma modules
# (zlib, liblzma and libbz2) and Apple's reference LZFSE encoder through the
# pyliblzfse package (pip install pyliblzfse).
#
# The decoded data is not stored: the suites regenerate it with the same
# generator (gen() here, vec_gen() in vec_gen.h), so the header holds only
# the encoded forms.
#
# Usage: python3 tests/unit/suites/codec/make_vectors.py > tests/unit/suites/codec/vectors.h

import bz2
import lzma
import sys
import zlib

import liblzfse

WORDS = [b"System", b"Folder", b"Finder", b"the", b"of", b"Macintosh", b"disk", b"file",
         b"resource", b"fork", b"INIT", b"cdev", b"{", b"}\r"]


def gen(kind, n, seed):
    # xorshift32, as vec_gen() in vec_gen.h
    x = seed

    def rnd():
        nonlocal x
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        return x

    out = bytearray()
    if kind == 0:  # text-like
        while len(out) < n:
            out += WORDS[rnd() % len(WORDS)] + b" "
    elif kind == 1:  # runs of one byte, 1..700 long
        while len(out) < n:
            v = rnd()
            out += bytes([v & 0xFF]) * (1 + (v >> 8) % 700)
    elif kind == 2:  # incompressible
        while len(out) < n:
            out.append(rnd() & 0xFF)
    else:  # zeros
        out = bytearray(n)
    return bytes(out[:n])


# name, generator kind, length, seed
DATA = [
    ("empty", 3, 0, 1),
    ("one", 2, 1, 7),
    ("small", 0, 150, 3),
    ("text3k", 0, 3000, 5),
    ("text", 0, 9000, 9),
    ("runs", 1, 300000, 11),
    ("random", 2, 600, 13),
    ("zeros", 3, 200000, 1),
    # Whole sectors, for the udif suite's chunks: 8 of text, and 128 (the
    # UDIF writer's chunk) of runs.
    ("sectors", 0, 4096, 21),
    ("sectors128", 1, 65536, 23),
]


def raw_deflate(b):
    c = zlib.compressobj(6, zlib.DEFLATED, -15)
    return c.compress(b) + c.flush()


# The data sets the variant encoders (other levels, checks and properties)
# run on; the main encoders run on all of them.
VARIANT_SETS = {"empty", "small", "text3k", "runs"}

# codec id (codec_id_t name), name, encoder, whether a variant
ENCODERS = [
    ("CODEC_ZLIB", "zlib", lambda b: zlib.compress(b, 6), False),
    ("CODEC_DEFLATE", "deflate", raw_deflate, False),
    ("CODEC_BZIP2", "bz9", lambda b: bz2.compress(b, 9), False),
    ("CODEC_BZIP2", "bz1", lambda b: bz2.compress(b, 1), True),
    ("CODEC_XZ", "xz", lambda b: lzma.compress(b), False),
    ("CODEC_XZ", "xz_crc32", lambda b: lzma.compress(b, check=lzma.CHECK_CRC32, preset=0), True),
    ("CODEC_XZ", "xz_lp", lambda b: lzma.compress(
        b, filters=[{"id": lzma.FILTER_LZMA2, "lc": 1, "lp": 3, "pb": 4}]), True),
    ("CODEC_LZMA_ALONE", "lzma", lambda b: lzma.compress(b, format=lzma.FORMAT_ALONE), True),
    ("CODEC_LZFSE", "lzfse", lambda b: liblzfse.compress(b), False),
]


def c_bytes(name, b):
    lines = [f"static const uint8_t {name}[{max(len(b), 1)}] = {{"]
    for i in range(0, len(b), 16):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in b[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = ["// SPDX-License-Identifier: MIT",
           "// Copyright (c) pappadf",
           "",
           "// vectors.h -- generated by make_vectors.py; do not edit.",
           "",
           "#include <stddef.h>",
           "#include <stdint.h>",
           "",
           "// Generated layout, kept as written (clang-format would repack it).",
           "// clang-format off",
           ""]
    table = []
    for dname, kind, n, seed in DATA:
        data = gen(kind, n, seed)
        for cid, ename, enc, variant in ENCODERS:
            if variant and dname not in VARIANT_SETS:
                continue
            b = enc(data)
            sym = f"v_{dname}_{ename}"
            out.append(c_bytes(sym, b))
            table.append(f"    {{\"{dname}/{ename}\", {cid}, {kind}, {n}u, {seed}u, {sym}, {len(b)}u}},")
    out.append("")
    out.append("// One vector: the codec, the data set that decodes from it (vec_gen's")
    out.append("// kind, length and seed) and the encoded bytes.")
    out.append("typedef struct {")
    out.append("    const char *name;")
    out.append("    int codec;")
    out.append("    int kind;")
    out.append("    size_t len;")
    out.append("    uint32_t seed;")
    out.append("    const uint8_t *enc;")
    out.append("    size_t enc_len;")
    out.append("} vector_t;")
    out.append("")
    out.append("static const vector_t k_vectors[] = {")
    out += table
    out.append("};")
    out.append("")
    out.append("// clang-format on")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
